// Copies the CarerPoint icons the family portal uses out of a carerpoint-ui checkout,
// until @lana-care/icons is published and installable here.
//   CP_UI_DIR=../carerpoint-ui bun scripts/vendor-cp-icons.ts
// shortcut: vendored copy, replace with the @lana-care/icons dependency once it is on the registry.
import { copyFileSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ui = process.env.CP_UI_DIR
if (!ui) throw new Error('Set CP_UI_DIR to a carerpoint-ui checkout')
const pkg = join(ui, 'packages/icons')
const root = join(import.meta.dir, '..')
const out = join(root, 'app/lib/cp-icons')
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version
const { icons } = await import(join(pkg, 'src/generated/registry.ts'))
const pascal = (n: string) => 'Cp' + n.split('-').map((s) => s[0]!.toUpperCase() + s.slice(1)).join('')
const byComponent = new Map<string, string>(Object.keys(icons).map((n) => [pascal(n), n]))

// Every CpX the app imports from ~/lib/cp-icons (a missing one also fails typecheck).
const walk = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]))
const used = new Set<string>()
for (const f of walk(join(root, 'app')).filter((f) => /\.(vue|ts)$/.test(f) && !f.includes('lib/cp-icons'))) {
  for (const m of readFileSync(f, 'utf8').matchAll(/import\s*\{([^}]+)\}\s*from\s*['"]~\/lib\/cp-icons['"]/g)) {
    for (const c of m[1]!.split(',').map((s) => s.trim()).filter(Boolean)) used.add(c)
  }
}
const names = [...used].sort().map((c) => {
  const n = byComponent.get(c)
  if (!n) throw new Error(`unknown icon component ${c}`)
  return [c, n] as const
})

const head = `// GENERATED by scripts/vendor-cp-icons.ts from @lana-care/icons ${version} — do not edit.\n`
writeFileSync(join(out, 'nodes.ts'), head + `import type { CpIconNode } from './types'\n\nexport const icons = {\n` +
  names.map(([, n]) => `  '${n}': ${JSON.stringify(icons[n])} as CpIconNode,`).join('\n') + `\n}\nexport type CpIconName = keyof typeof icons\n`)
// Per-icon components, so call sites keep @lana-care/icons' `CpX` API and switch back with an import path.
writeFileSync(join(out, 'components.ts'), head + `import { h, type FunctionalComponent } from 'vue'
import CpIcon from '~/components/CpIcon.vue'
import type { CpIconAnimate, CpIconTone } from './types'
import type { CpIconName } from './nodes'

export interface CpIconProps { size?: number | string; tone?: CpIconTone; animate?: CpIconAnimate; label?: string }
const icon = (name: CpIconName): FunctionalComponent<CpIconProps> => (_, { attrs }) => h(CpIcon, { ...attrs, name })

` + names.map(([c, n]) => `export const ${c} = icon('${n}')`).join('\n') + '\n')
writeFileSync(join(out, 'index.ts'), head + `export * from './components'\n`)
// Extensionless relative imports: the Nuxt app resolves them, `.js` would not.
for (const f of ['core.ts', 'types.ts']) writeFileSync(join(out, f), head + readFileSync(join(pkg, 'src', f), 'utf8').replace(/from '\.\/(\w+)\.js'/g, "from './$1'"))
copyFileSync(join(pkg, 'src/icons.css'), join(root, 'app/assets/css/cp-icons.css'))
console.log(`vendored ${names.length} icons from @lana-care/icons ${version}`)
